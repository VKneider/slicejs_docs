import fs from 'fs';
import path from 'path';
import { GROUP_ORDER, SECTION_ORDER } from './navConfig.js';

// The navigation tree is generated from the same front matter that generates
// the pages. Before this, `documentationRoutes.js` was hand-maintained and had
// already drifted from `docsIndex.js` (5 groups in the tree, 9 in the index).
//
// To change the order, edit `section`, `group` and `order` in the page's
// markdown; to add a section, add it to SECTION_ORDER on purpose.
const escapeValue = (value) => String(value ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const compareEntries = (a, b) => {
  if (a.order !== b.order) return a.order - b.order;
  return String(a.title).localeCompare(String(b.title));
};

const sectionKey = (title) => title
  .toLowerCase()
  .replace(/&/g, 'and')
  .replace(/[^a-z0-9]+/g, ' ')
  .trim()
  .split(' ')
  .map((word, index) => (index === 0 ? word : word.charAt(0).toUpperCase() + word.slice(1)))
  .join('');

const groupKey = (title) => title
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '');

const toItem = (entry) => ({
  title: entry.navLabel || entry.title,
  path: entry.route,
  component: entry.component
});

const formatItems = (items, indent) => {
  const pad = ' '.repeat(indent);
  if (!items.length) return '[]';

  const rows = items.map((item) => {
    if (item.items) {
      return `${pad}  {\n${pad}    title: '${escapeValue(item.title)}',\n${pad}    items: ${formatItems(item.items, indent + 4)}\n${pad}  }`;
    }
    return `${pad}  {\n${pad}    title: '${escapeValue(item.title)}',\n${pad}    path: '${escapeValue(item.path)}',\n${pad}    component: '${escapeValue(item.component)}'\n${pad}  }`;
  });

  return `[\n${rows.join(',\n')}\n${pad}]`;
};

/**
 * Build the generated navigation module.
 *
 * @param {Array<Record<string, any>>} entries front matter entries (docsIndex input)
 * @returns {string}
 */
export const buildDocumentationRoutes = (entries = []) => {
  const pages = entries
    .filter((entry) => entry.route && entry.title)
    .filter((entry) => entry.route !== '/Documentation')
    .map((entry) => ({
      ...entry,
      order: Number(entry.order) || 0,
      component: String(entry.component || '').trim()
    }));

  const missingComponent = pages.filter((entry) => !entry.component);
  if (missingComponent.length) {
    throw new Error(
      `Navigation entries without a component:\n${missingComponent
        .map((entry) => `- ${entry.route} (${entry.title})`)
        .join('\n')}`
    );
  }

  const bySection = new Map();
  for (const entry of pages) {
    const section = entry.section || 'Other';
    if (!bySection.has(section)) bySection.set(section, []);
    bySection.get(section).push(entry);
  }

  const unknownSections = [...bySection.keys()].filter((section) => !SECTION_ORDER.includes(section));
  if (unknownSections.length) {
    throw new Error(
      `Unknown docs sections: ${unknownSections.join(', ')}. Add them to SECTION_ORDER in parser/lib/tree.js.`
    );
  }

  const sections = SECTION_ORDER
    .filter((title) => bySection.has(title))
    .map((title) => {
      const sectionEntries = bySection.get(title).sort(compareEntries);
      const grouped = new Map();
      for (const entry of sectionEntries) {
        const group = entry.group || '';
        if (!grouped.has(group)) grouped.set(group, []);
        grouped.get(group).push(entry);
      }

      const hasGroups = [...grouped.keys()].some(Boolean);
      if (!hasGroups) {
        return {
          key: sectionKey(title),
          title,
          items: sectionEntries.map(toItem)
        };
      }

      // Sections that mix ungrouped pages with groups keep the ungrouped pages
      // first; the named groups follow in the order declared here.
      const items = [];
      for (const entry of grouped.get('') || []) items.push(toItem(entry));

      const names = [...grouped.keys()].filter(Boolean);
      const declared = GROUP_ORDER[title] || [];
      const ordered = [
        ...declared.filter((name) => names.includes(name)),
        ...names.filter((name) => !declared.includes(name)).sort((a, b) => a.localeCompare(b))
      ];

      for (const name of ordered) {
        items.push({
          key: groupKey(name),
          title: name,
          items: (grouped.get(name) || []).sort(compareEntries).map(toItem)
        });
      }

      return { key: sectionKey(title), title, items };
    });

  const defaultEntry = entries.find((entry) => entry.route === '/Documentation');
  const defaultRoute = {
    path: '/Documentation',
    component: defaultEntry?.component || 'Documentation'
  };

  const module = `// GENERATED by parser/lib/tree.js - do not edit by hand.
// Edit section/group/order in the page front matter, then run docs:generate.

export const documentationRoutes = {
  sections: [
${sections.map((section) => `    {
      key: '${escapeValue(section.key)}',
      title: '${escapeValue(section.title)}',
      items: ${formatItems(section.items, 6)}
    }`).join(',\n')}
  ],
  defaultRoute: {
    path: '${escapeValue(defaultRoute.path)}',
    component: '${escapeValue(defaultRoute.component)}'
  }
};

export const getAllRoutes = (routesObj) => {
  const allRoutes = [];
  const visit = (item) => {
    if (!item) return;
    if (item.path && item.component) {
      allRoutes.push({ path: item.path, component: item.component });
    }
    for (const child of item.items || []) visit(child);
  };

  visit(routesObj.defaultRoute);
  for (const section of routesObj.sections || []) visit(section);
  return allRoutes;
};

export const createTreeViewItems = (routesObj) => {
  const toTreeItems = (items) => (items || []).map((item) => {
    if (item.items) {
      return {
        value: item.title,
        items: toTreeItems(item.items)
      };
    }
    return {
      value: item.title,
      path: item.path,
      component: item.component
    };
  });

  return (routesObj.sections || []).map((section) => ({
    value: section.title,
    items: toTreeItems(section.items)
  }));
};
`;

  return module;
};

export const writeDocumentationRoutes = (entries, outputPath) => {
  const content = buildDocumentationRoutes(entries);
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, content, 'utf8');
  return content;
};
